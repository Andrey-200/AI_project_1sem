
import json
from datetime import datetime

import ollama


MODEL = "qwen3:8b"
DATA_FILE = "data.json"
FEEDBACK_FILE = "feedback.jsonl"


# Загрузка данных
def load_data():
    with open(DATA_FILE, "r", encoding="utf-8") as file:
        data = json.load(file)

    required_fields = [
        "document_id",
        "document_type",
        "case_type",
        "text",
        "annotation"
    ]

    for field in required_fields:
        if field not in data:
            raise ValueError(f"В данных отсутствует поле: {field}")

    if not isinstance(data["annotation"], dict):
        raise ValueError("Поле annotation должно быть объектом JSON")

    return data


# Подготовка аннотации
def prepare_annotation(data):
    return json.dumps(
        data["annotation"],
        ensure_ascii=False,
        indent=2
    )


# Первый этап: формирование внутреннего костяка
def generate_report_skeleton(data):
    system_prompt = """
Ты — аналитический помощник по судебным документам.

Твоя задача — сформировать внутренний костяк будущего
информационного отчёта на основании структурированной аннотации.

ПРАВИЛА:

1. Используй только сведения из аннотации.
2. Не придумывай отсутствующие сведения.
3. Точно сохраняй даты, числа, ФИО, номера дел и статьи.
4. Отражай предупреждения и противоречия аннотации.
5. Не делай самостоятельных юридических выводов.
6. Не оценивай законность решения суда.
7. Не оценивай правильность квалификации и наказания.

СТРУКТУРА:

- Общая информация о документе.
- Суд и участники процесса.
- Обстоятельства дела.
- Квалификация, указанная в документе.
- Результат рассмотрения дела.
- Назначенное наказание.
- Особые замечания.

Это промежуточный материал.
Не добавляй вступлений и заключений.
"""

    user_prompt = f"""
Тип документа: {data["document_type"]}
Тип дела: {data["case_type"]}

Аннотация:
{prepare_annotation(data)}

Сформируй внутренний костяк отчёта.
"""

    response = ollama.chat(
        model=MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        options={
            "temperature": 0.1,
            "num_ctx": 8192
        }
    )

    return response["message"]["content"]


# Второй этап: формирование полноценного отчёта
def enrich_report(data, skeleton):
    system_prompt = """
Ты — помощник по подготовке информационных отчётов
на основании судебных документов Российской Федерации.

Твоя задача — создать единый полноценный отчёт,
объединив аннотацию, внутренний костяк и полный текст документа.

ПРИОРИТЕТ ИСТОЧНИКОВ:

1. Аннотация — основной источник структурированных сведений.
2. Костяк — основа структуры отчёта.
3. Полный текст — источник подробностей и контекста.

ОБЯЗАТЕЛЬНЫЕ ПРАВИЛА:

1. Не изменяй значения аннотации.
2. Не заменяй числа, даты, ФИО, номера дел и статьи.
3. Не смешивай обстоятельства текущего дела
   с обстоятельствами предыдущих судебных решений.
4. Не придумывай отсутствующие факты.
5. Не приписывай участникам слова и действия,
   которых нет в документе.
6. Не делай самостоятельных юридических выводов.
7. Не оценивай законность решения суда.
8. Не оценивай правильность квалификации или наказания.
9. Не путай номер главы с номером статьи.
10. Если текст противоречит аннотации, не исправляй её.
    Укажи противоречие в отдельном разделе.

РАБОТА С ИНФОРМАЦИЕЙ:

1. Используй костяк как структуру итогового отчёта.
2. Дополняй каждый раздел подробностями из полного текста.
3. Встраивай новые сведения в подходящие разделы.
4. Не повторяй уже изложенную информацию.
5. Не создавай несколько разделов с одинаковым содержанием.
6. Не добавляй подробности, не относящиеся к делу.
7. Если информации для раздела нет, не выдумывай её.

ЮРИДИЧЕСКАЯ ТЕРМИНОЛОГИЯ:

Используй корректные обозначения:
- судья;
- секретарь судебного заседания;
- государственный обвинитель;
- защитник;
- подсудимый / подсудимая;
- потерпевший / потерпевшая;
- осуждённый / осуждённая.

Соблюдай грамматический род участников согласно документу.
Не заменяй юридические термины бытовыми словами.
Не используй бессмысленные или искусственно образованные слова.

СТРУКТУРА ИТОГОВОГО ОТЧЁТА:

1. Общая информация о документе.
2. Суд и участники процесса.
3. Обстоятельства дела.
4. Ход судебного разбирательства.
5. Позиции участников процесса.
6. Результат рассмотрения дела.
7. Назначенное наказание.
8. Особые замечания и расхождения.

ТРЕБОВАНИЯ К ВЫВОДУ:

1. Выведи только полноценный итоговый отчёт.
2. Не показывай промежуточный костяк.
3. Не показывай аннотацию.
4. Не добавляй список использованных источников.
5. Не добавляй примечание о том, на основании чего
   сформирован отчёт.
6. Не добавляй заключение о работе искусственного интеллекта.
7. Не добавляй фразы о том, что юридическая оценка
   не проводилась.
8. Не описывай этапы генерации.
9. Не добавляй вступление перед отчётом.
10. Не добавляй заключение после последнего раздела.

Отчёт должен завершаться последним содержательным разделом.
"""

    user_prompt = f"""
АННОТАЦИЯ:
{prepare_annotation(data)}

ВНУТРЕННИЙ КОСТЯК:
{skeleton}

ПОЛНЫЙ ТЕКСТ СУДЕБНОГО ДОКУМЕНТА:
{data["text"]}

Создай единый полноценный отчёт.
Используй костяк как основу, а полный текст для дополнения.
Сохрани все значения аннотации.
Выведи только сам отчёт без дополнительных комментариев.
"""

    response = ollama.chat(
        model=MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        options={
            "temperature": 0.1,
            "num_ctx": 8192
        }
    )

    return response["message"]["content"].strip()


# Генерация итогового отчёта
def create_full_report(data):
    print("\nФормирование отчёта...\n")

    # Внутренний этап: костяк
    skeleton = generate_report_skeleton(data)

    # Второй этап: полноценный отчёт
    report = enrich_report(data, skeleton)

    print("\n" + "=" * 60)
    print("ИТОГОВЫЙ ОТЧЁТ")
    print("=" * 60)
    print(report)
    print("=" * 60)

    return report


# Контекст для диалога
def prepare_context(data, report):
    return f"""
Ты — чат-помощник по судебному документу.

Отвечай на вопросы пользователя по содержанию документа.

ПРАВИЛА:

1. Не придумывай факты.
2. Используй аннотацию как основной источник структурированных сведений.
3. Используй полный текст для уточнения подробностей.
4. Не изменяй значения аннотации.
5. Если сведения противоречат друг другу, укажи на расхождение.
6. Не путай номера глав и статей.
7. Не выдавай предположения за факты.
8. Не делай юридических выводов без отдельного запроса.
9. Если информации нет, сообщи об этом.
10. Отвечай непосредственно на вопрос, без лишних вступлений.

АННОТАЦИЯ:
{prepare_annotation(data)}

ПОЛНЫЙ ТЕКСТ:
{data["text"]}

ИТОГОВЫЙ ОТЧЁТ:
{report}
"""


# Сохранение обратной связи
def save_feedback(user_input, document_id):
    feedback = {
        "document_id": document_id,
        "date": datetime.now().isoformat(),
        "feedback": user_input
    }

    if user_input.lower().startswith("legal:"):
        feedback["agent"] = "legal_agent"
    else:
        feedback["agent"] = "triage"

    with open(FEEDBACK_FILE, "a", encoding="utf-8") as file:
        file.write(json.dumps(feedback, ensure_ascii=False) + "\n")

    print("Обратная связь сохранена.")


# Основная программа
def main():
    data = load_data()

    report = create_full_report(data)

    system_context = prepare_context(data, report)

    messages = [
        {
            "role": "system",
            "content": system_context
        }
    ]

    print("\n" + "=" * 60)
    print("ДИАЛОГ С ДОКУМЕНТОМ")
    print("Введите /exit для выхода.")
    print("Введите /feedback для обратной связи.")
    print("=" * 60)

    while True:
        user_input = input("\nВы: ").strip()

        if user_input.lower() == "/exit":
            print("Завершение работы.")
            break

        if user_input.lower() == "/feedback":
            feedback_text = input("Опишите замечание: ").strip()

            if feedback_text:
                save_feedback(feedback_text, data["document_id"])

            continue

        if not user_input:
            continue

        messages.append({
            "role": "user",
            "content": user_input
        })

        try:
            response = ollama.chat(
                model=MODEL,
                messages=messages,
                options={
                    "temperature": 0.2,
                    "num_ctx": 8192
                }
            )

            answer = response["message"]["content"]

            print("\nПомощник:", answer)

            messages.append({
                "role": "assistant",
                "content": answer
            })

        except Exception as error:
            print("Ошибка Ollama:", error)


if __name__ == "__main__":
    main()
